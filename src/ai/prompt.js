/** Схема ответа: модель обязана вернуть вердикт по каждому запросу. */
export const RESPONSE_SCHEMA = {
  type: 'object',
  properties: {
    results: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          term: { type: 'string' },
          verdict: { type: 'string', enum: ['relevant', 'irrelevant', 'doubtful'] },
          reason: { type: 'string' },
          negative_root: { type: 'string' },
        },
        required: ['term', 'verdict', 'reason'],
      },
    },
  },
  required: ['results'],
};

function describeProfile(profile) {
  const lines = [
    `Что продаёт: ${profile.sells || 'не указано'}`,
    `Чего НЕ делает: ${profile.notDoing || 'не указано'}`,
    `География работы: ${(profile.geo ?? []).join(', ') || 'не указана'}`,
  ];
  if (profile.ownBrand) lines.push(`Собственный бренд: ${profile.ownBrand}`);
  if ((profile.competitors ?? []).length > 0) {
    lines.push(`Бренды конкурентов: ${profile.competitors.join(', ')}`);
  }
  return lines.join('\n');
}

/**
 * Собирает запрос к модели.
 * @param {string[]} terms тексты поисковых запросов
 * @param {object} profile профиль проекта
 * @returns {string}
 */
export function buildUserPrompt(terms, profile) {
  return [
    'ПРОФИЛЬ РЕКЛАМОДАТЕЛЯ',
    describeProfile(profile),
    '',
    `ПОИСКОВЫЕ ЗАПРОСЫ (${terms.length} шт.)`,
    ...terms.map((term, index) => `${index + 1}. ${term}`),
    '',
    'Верни вердикт по каждому запросу. Поле term копируй дословно.',
  ].join('\n');
}
